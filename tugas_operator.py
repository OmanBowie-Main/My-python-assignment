# input nilainya
nilai1 = 100
nilai2 = 80

# Contoh operator penugasan
a = 10
a += 5  
# penugasan bertambah
print("Operator penugasan (a += 5):", a)

# Contoh operator logika
hasil_logika = (nilai1 > nilai2) and (nilai1 != 0)
print("Operator logika (and):", hasil_logika)

# Contoh operator bitwise
hasil_bitwise = nilai1 & nilai2
print("Operator bitwise (&):", hasil_bitwise)

# Contoh operator identitas
lst1 = [nilai1, nilai2]
lst2 = lst1
print("Operator identitas (is):", lst1 is lst2)

# Contoh operator keanggotaan
print("Operator keanggotaan (in):", nilai1 in lst1)