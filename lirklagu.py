def jalanin_lirik():
   
    lirik = [
        [
            ("When you go", 0.30), 
            (", and would you even turn to", 0.15),
            (" say", 0.20),
        ],
        [
            ("\"I don't love you", 0.15), 
            (" like I did yesterday\"?", 0.09),  
        ],
    ]

    
    delay_baris = [0.3, 0.5]
    
    # Judul lagu
    print("\n== I Don't Love You - My Chemical Romance (MCR) ==")
    
    for i, baris in enumerate(lirik):
        for bagian in baris:
            teks, delay_karakter = bagian
            for karakter in teks:
                print(karakter, end='')
                sys.stdout.flush()
                time.sleep(delay_karakter)
        time.sleep(delay_baris[i])
        print('')
    
    # Nama pembuat
    print("// Code by Renal Ali Syahid")
    
    # Logo MCR (My Chemical Romance)
    print_mcr_logo()


